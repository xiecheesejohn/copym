//! macOS backend. AppKit offers no clipboard-change notification, so we poll the
//! (very cheap) `NSPasteboard.changeCount` and only read when it changes.
//!
//! Skips content marked per the nspasteboard.org conventions used by 1Password,
//! Bitwarden, KeePassXC, Keychain etc.

use super::arboard_io::{self, ArboardWriter};
use super::{ClipEvent, Monitor, MonitorOptions};
use objc2::rc::autoreleasepool;
use objc2::MainThreadMarker;
use objc2_app_kit::{NSApplication, NSApplicationActivationPolicy, NSPasteboard, NSWorkspace};
use std::sync::mpsc::Sender;
use std::time::Duration;

const SECRET_TYPES: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "de.petermaurer.TransientPasteboardType",
    "Pasteboard generator type",
];

pub fn start(tx: Sender<ClipEvent>, opts: MonitorOptions) -> Result<Monitor, String> {
    let interval = Duration::from_millis(opts.poll_interval_ms.clamp(100, 5000));
    std::thread::Builder::new()
        .name("clip-poller".into())
        .spawn(move || {
            let mut clip = match arboard::Clipboard::new() {
                Ok(c) => c,
                Err(e) => {
                    eprintln!("copym: clipboard unavailable: {e}");
                    return;
                }
            };
            let mut last = autoreleasepool(|_| NSPasteboard::generalPasteboard().changeCount());
            loop {
                std::thread::sleep(interval);
                let probe = autoreleasepool(|_| {
                    let pb = NSPasteboard::generalPasteboard();
                    let count = pb.changeCount();
                    if count == last {
                        return None;
                    }
                    let types: Vec<String> =
                        pb.types().map(|a| a.iter().map(|t| t.to_string()).collect()).unwrap_or_default();
                    let source = NSWorkspace::sharedWorkspace()
                        .frontmostApplication()
                        .and_then(|app| app.localizedName())
                        .map(|n| n.to_string());
                    Some((count, types, source))
                });
                let Some((count, types, source)) = probe else { continue };
                last = count;
                if opts.respect_password_hints && types.iter().any(|t| SECRET_TYPES.contains(&t.as_str())) {
                    continue;
                }
                if let Some(content) = arboard_io::read(&mut clip, &opts) {
                    let _ = tx.send(ClipEvent { content, source });
                }
            }
        })
        .map_err(|e| e.to_string())?;

    let writer = ArboardWriter::spawn()?;
    let run = || -> Result<(), String> {
        let mtm = MainThreadMarker::new().ok_or("daemon must run on the main thread")?;
        let app = NSApplication::sharedApplication(mtm);
        // No Dock icon, no menu bar: a pure background agent.
        app.setActivationPolicy(NSApplicationActivationPolicy::Accessory);
        app.run();
        Ok(())
    };
    Ok(Monitor { backend: "macos (NSPasteboard)", supports_hotkey: true, writer: Box::new(writer), run: Box::new(run) })
}
